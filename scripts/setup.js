'use strict';
// Creates backend/.env interactively (beginner friendly). Usage: node scripts/setup.js [--force]
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { ask } = require('./prompt');

const ENV_PATH = path.join(__dirname, '..', '.env');

(async () => {
  if (fs.existsSync(ENV_PATH) && !process.argv.includes('--force')) {
    console.log('backend\\.env already exists. Use "node scripts/setup.js --force" to recreate it.');
    return;
  }
  console.log('\n=== KeyFort first-time setup ===\n');
  console.log('Where should KeyFort store its data?');
  console.log('  1) Local MongoDB installed on this computer (default)');
  console.log('  2) MongoDB Atlas (free cloud database, no installation)\n');
  const choice = (await ask('Type 1 or 2 and press Enter [1]: ')) || '1';
  let uri = 'mongodb://127.0.0.1:27017/keyfortDB';
  if (choice === '2') {
    console.log('\nPaste your Atlas connection string. It looks like:');
    console.log('mongodb+srv://USER:PASSWORD@cluster0.xxxxx.mongodb.net/keyfortDB?retryWrites=true&w=majority\n');
    uri = await ask('Connection string: ');
    if (!/^mongodb(\+srv)?:\/\//.test(uri)) {
      console.error('\nThat does not look like a MongoDB connection string. Run setup again.');
      process.exit(1);
    }
  }
  const port = (await ask('Port for the website [5000]: ')) || '5000';
  const secret = crypto.randomBytes(48).toString('hex');
  const content = `# Generated by scripts/setup.js on ${new Date().toISOString()}. Never share or commit this file.
NODE_ENV=development
PORT=${Number(port) || 5000}
HOST=127.0.0.1
MONGODB_URI=${uri}
MONGODB_DB_NAME=keyfortDB
SESSION_SECRET=${secret}
SESSION_MAX_AGE_MIN=480
COOKIE_SAMESITE=lax
CLIENT_URL=http://localhost:${Number(port) || 5000},http://localhost:5173
TRUST_PROXY=0
MAX_FAILED_ATTEMPTS=5
LOCK_MINUTES=15
RESET_TOKEN_MINUTES=30
BCRYPT_ROUNDS=12
`;
  fs.writeFileSync(ENV_PATH, content, { mode: 0o600 });
  console.log('\nSaved backend\\.env (a random session secret was generated for you).');
})();
